#!/usr/bin/env python3
"""Write the synthetic example patterns in examples/ (used by the Quick Start).

Both files are simulated, not measured, so the true answer is known:

- examples/lab6_synthetic.txt: a LaB6 standard (NIST SRM 660c lattice parameter) with
  instrument broadening only, for ``xrd-analysis calibrate``.
- examples/cu_synthetic.txt: five Cu reflections from 40 nm cube-shaped crystallites without
  microstrain, measured on the same instrument, for ``xrd-analysis analyze``.

Each reflection is a Cu Kα1 + Kα2 pair (Bragg positions for each wavelength, I(Kα2)/I(Kα1) =
0.5) with an exact Voigt profile (scipy.special.voigt_profile, independent of the fitting code
in xrd_analysis). The Gaussian part is the instrument width from the Caglioti equation; the
Lorentzian part is the Scherrer size width K λ / (D cos θ), with K for cube-shaped grains
(Langford & Wilson 1978). A smooth background and Poisson counting noise (fixed seed) are added.

Usage: python scripts/make_example_data.py
"""

from __future__ import annotations

import math
import sys
from pathlib import Path

import numpy as np
from scipy.special import voigt_profile

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from xrd_analysis.core.constants import CU_KA1, CU_KA2, KA2_KA1_RATIO  # noqa: E402
from xrd_analysis.core.copper_crystal import get_k_for_hkl  # noqa: E402

OUT = ROOT / "examples"
SEED = 2026
STEP = 0.02  # degrees 2θ

# Instrument (illustrative laboratory diffractometer, Gaussian): FWHM² = U tan²θ + V tanθ + W
U, V, W = 0.01, -0.005, 0.004

# Cu: a = 3.6150 Å, relative integrated intensities of the powder pattern (JCPDS 04-0836)
A_CU = 3.6150
CU_REFLECTIONS = {(1, 1, 1): 100, (2, 0, 0): 46, (2, 2, 0): 20, (3, 1, 1): 17, (2, 2, 2): 5}
D_TRUE_NM = 40.0

# LaB6: a = 4.156826 Å (NIST SRM 660c); illustrative relative intensities
A_LAB6 = 4.156826
LAB6_REFLECTIONS = {
    (1, 0, 0): 60, (1, 1, 0): 100, (1, 1, 1): 40, (2, 0, 0): 25, (2, 1, 0): 55,
    (2, 1, 1): 30, (2, 2, 0): 15, (3, 0, 0): 35, (3, 1, 0): 25, (3, 1, 1): 12,
}


def bragg_two_theta(hkl: tuple[int, int, int], a: float, wavelength: float) -> float:
    d = a / math.sqrt(sum(i * i for i in hkl))
    return 2 * math.degrees(math.asin(wavelength / (2 * d)))


def instrument_fwhm(two_theta: float) -> float:
    t = math.tan(math.radians(two_theta / 2))
    return math.sqrt(U * t * t + V * t + W)


def size_fwhm(two_theta: float, wavelength: float, k: float, d_nm: float) -> float:
    return math.degrees(k * wavelength / (d_nm * 10 * math.cos(math.radians(two_theta / 2))))


def pattern(x, reflections, a, size_nm, peak_area, background, rng):
    """Counts on grid x for the given reflections (size_nm None: instrument width only)."""
    y = background(x)
    for hkl, rel in reflections.items():
        k = get_k_for_hkl(*hkl)
        for wavelength, weight in ((CU_KA1, 1.0), (CU_KA2, KA2_KA1_RATIO)):
            tt = bragg_two_theta(hkl, a, wavelength)
            f_g = instrument_fwhm(tt)
            f_l = size_fwhm(tt, wavelength, k, size_nm) if size_nm else 0.0
            sigma = f_g / (2 * math.sqrt(2 * math.log(2)))
            y = y + peak_area * rel / 100 * weight * voigt_profile(x - tt, sigma, f_l / 2)
    return rng.poisson(y).astype(int)


def write(path: Path, x, counts, header: list[str]) -> None:
    lines = [f"; {h}" for h in header] + ["[Data]", "Angle,PSD"]
    lines += [f"{a:.2f},{c}" for a, c in zip(x, counts)]
    path.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {path.relative_to(ROOT)} ({len(x)} points)")


def main() -> None:
    OUT.mkdir(exist_ok=True)
    rng = np.random.default_rng(SEED)
    inst = f"instrument: Gaussian, Caglioti U = {U}, V = {V}, W = {W} deg^2"
    common = ["Cu Ka1 + Ka2 (I2/I1 = 0.5), exact Voigt profiles, Poisson noise",
              "generated by scripts/make_example_data.py; simulated, not a measurement"]

    x = np.round(np.arange(20.0, 80.0 + STEP / 2, STEP), 2)
    counts = pattern(x, LAB6_REFLECTIONS, A_LAB6, None, 1500.0,
                     lambda t: 150 + 250 * np.exp(-(t - 20) / 12), rng)
    write(OUT / "lab6_synthetic.txt", x, counts,
          ["Synthetic LaB6 standard (a = 4.156826 A, NIST SRM 660c), instrument broadening only", inst] + common)

    x = np.round(np.arange(40.0, 100.0 + STEP / 2, STEP), 2)
    counts = pattern(x, CU_REFLECTIONS, A_CU, D_TRUE_NM, 4000.0,
                     lambda t: 120 + 80 * np.exp(-(t - 40) / 20), rng)
    write(OUT / "cu_synthetic.txt", x, counts,
          [f"Synthetic Cu pattern: true crystallite size {D_TRUE_NM:g} nm (cube-shaped, K from Langford & Wilson 1978), "
           "no microstrain", inst] + common)


if __name__ == "__main__":
    main()
